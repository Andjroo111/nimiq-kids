// Writes public/js/lib/phosphor.js: the Phosphor glyphs nimiq.kids ships, inlined, three
// weights each (regular, bold, duotone with the shade at Nimiq's 0.4), from
// @iconify-json/ph. Run by hand after editing tools/icons/phosphor-list.json; the output is
// committed, so the tablet never fetches an icon and the parent's picker is one JS object.
//
// Why Phosphor, and why inlined: docs/NEXT-SESSION.md 2026-09-15 (the icon pack research).
// Andjroo: "is there an icon pack that would match nimiq-ui? I don't want to be generating
// these all the time." Phosphor is MIT, reads closest to Nimiq's own Streamline-drawn set,
// and has every glyph a kids app needs. Nimiq's own glyphs stay verbatim where Nimiq has one.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const set = require("@iconify-json/ph/icons.json");
const list = JSON.parse(readFileSync(new URL("./phosphor-list.json", import.meta.url), "utf8"));

// Only the weights each name is drawn at ship: the catalogue is duotone (a Treasure Box tile,
// the parent's picker), the chrome is regular and bold (one weight per size step, icons.css).
// Every weight of every name would be 250 KB; this is about half.
const catalog = [...new Set(Object.values(list.catalog).flat())];
const names = [...new Set([...catalog, ...list.chrome])];
const body = (n) => {
  const i = set.icons[n];
  if (!i) throw new Error(`not in @iconify-json/ph: ${n}`);
  return i.body;
};
const glyphs = {};
for (const n of names) {
  const g = {};
  if (list.chrome.includes(n)) { g.r = body(n); g.b = body(`${n}-bold`); }
  // Nimiq's two-tone rule: the secondary shape is the SAME colour at 0.4 (nimiq-ui skill,
  // Icons). Phosphor ships it at 0.2; rewritten here so no renderer has to know.
  if (catalog.includes(n) || list.duotone.includes(n)) g.d = body(`${n}-duotone`).replace(/opacity="\.2"/g, 'opacity=".4"');
  glyphs[n] = g;
}
const out = `// GENERATED by tools/icons/build-phosphor.mjs from tools/icons/phosphor-list.json. Do not edit.
// Phosphor Icons (MIT) https://phosphoricons.com, ${names.length} glyphs x 3 weights.
// r = regular, b = bold, d = duotone (shade at 0.4, Nimiq's two-tone value).
export const PH = ${JSON.stringify(glyphs)};
/** What a parent may pick for a shelf or a thing to give the kid, by category, in order. */
export const PH_CATALOG = ${JSON.stringify(list.catalog)};
/** One Phosphor glyph as an <svg>. weight: "r" | "b" | "d". Colour is currentColor. */
export function ph(name, weight = "r", cls = "") {
  const g = PH[name]; if (!g) return "";
  return \`<svg class="ph \${cls}" viewBox="0 0 256 256" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">\${g[weight] ?? g.r ?? g.b ?? g.d}</svg>\`;
}
`;
writeFileSync(new URL("../../public/js/lib/phosphor.js", import.meta.url), out);
console.log(`phosphor.js: ${names.length} glyphs, ${(out.length / 1024).toFixed(0)} KB`);
