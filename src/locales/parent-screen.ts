// nimiq.kids parent app — SCREEN CONTROL: the lock override on a kid's page (#304).
// Split out of parent.ts because that file sits at the edge of this repo's 800-line CI
// guard, and the guard is `>=`, so the keys below could not have gone back into it.
//
// The `ovr.` shape of these names is not decoration: `papp.lock*` already belongs to the
// lock WINDOWS in parent-board.ts (#303), which are a rule about every future Tuesday.
// These are the manual override, which is a sentence about right now. Two features, one
// tablet, and a shared prefix would have made every grep return both.
//
// Same rules as every other locale file here: English is authoritative, the other four
// mirror its keys exactly (the parity test walks the MERGED set), sentence case, no
// periods on titles or buttons, no em/en dashes (nimiq-ui rules 16/18).
//
// "A grown-up", never "you": `lock_overrides` records an AUTHOR but not a MEMBER, and a
// household can hold several grown-ups (#291). Telling a co-parent "you locked it" when
// the other one did is worse than not naming them.
//
// The `scr.` block below (#305) is the one place "you" is right, and the difference is
// tense. Those lines are not about who DID something: they are what the tablet is doing
// now, and the waiting one is a request to whoever is holding this phone — who can answer
// it, supporter included. "Waiting for a grown-up" on the grown-up's own screen reads as
// somebody else's problem.

