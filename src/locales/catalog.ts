// nimiq.kids — the titles WE author, in the 5 languages the shell ships.
//
// These back src/title-catalog.ts. A row that carries a `title_key` renders
// `t(key)` here; a row without one is the parent's own words and is printed
// exactly as typed, in every language. See title-catalog.ts for why.
//
// Merged into BOTH app locale sets (the kid board and the parent's approval
// queue name the same chores), which is why they live in their own file rather
// than inside en.ts — one translation of "Brush your teeth", not two that drift.
//
// Same rules as everywhere else: English is authoritative, the other four mirror
// its keys exactly (parity tests in locales.test.ts and parent-locales.test.ts,
// both of which also assert every key title-catalog.ts declares is present),
// sentence case, no em/en dashes.
//
// These are read ALOUD by parents to small children and read BY kids who are
// learning to read, so the register is deliberately plain: the imperative a
// parent would actually use at home, not the infinitive a UI usually prefers.
// Spanish/French/Portuguese use the informal second person throughout (tú / tu),
// German uses du, and possessives stay in ("your bed", not "the bed") because
// the whole board is addressed to one child.

